static uint8_t map_mem[64*64];

static void tick(Vdda_core* d) {
    d->clk = 0; d->eval();
    d->clk = 1; d->eval();
}

static uint32_t to_q1616(double f) {
    return (uint32_t)(int32_t)(f * 65536.0);
}

int main(int argc, char** argv) {
    Verilated::commandArgs(argc, argv);

    // Build map memory
    for (int y = 0; y < 64; y++)
        for (int x = 0; x < 64; x++)
            map_mem[y*64+x] = (MAP[y][x] == '1') ? 1 : 0;

    Vdda_core* dut = new Vdda_core;

    // Reset
    dut->rst_n = 0;
    dut->start = 0;
    dut->map_read_data = 0;
    for (int i = 0; i < 3; i++) tick(dut);
    dut->rst_n = 1;
    tick(dut);

    // Reference output from Python raycaster
    const char* ref = "****++++++++++++++========----::::.................::::::---------============++";

    char rtl_output[81] = {};

    uint32_t px = to_q1616(2.5);
    uint32_t py = to_q1616(2.5);
    uint32_t pa = 0; // angle 0 = east

    int pass = 0, fail = 0;

    for (int col = 0; col < 80; col++) {
        // Drive start
        dut->player_x     = px;
        dut->player_y     = py;
        dut->player_angle = pa;
        dut->col_index    = (uint8_t)col;
        dut->start = 1;
        tick(dut);
        dut->start = 0;

        // Run until done, feeding map reads
        char got_char = '.';
        int timeout = 500;
        while (timeout-- > 0) {
            // Feed map data (1-cycle latency: addr stable this cycle, data next)
            uint32_t addr = dut->map_read_addr;
            if (addr < 64*64)
                dut->map_read_data = map_mem[addr];
            else
                dut->map_read_data = 0;

            tick(dut);

            if (dut->done) {
                got_char = (char)dut->ascii_char;
                break;
            }
        }
        rtl_output[col] = got_char;
    }
    rtl_output[80] = '\0';

    printf("REF: %s\n", ref);
    printf("RTL: %s\n", rtl_output);

    // Compare
    int match = 1;
    for (int i = 0; i < 80; i++) {
        if (rtl_output[i] != ref[i]) {
            printf("MISMATCH col %d: RTL='%c' REF='%c'\n", i, rtl_output[i], ref[i]);
            match = 0;
        }
    }
    if (match) {
        printf("PASS: RTL output matches Python reference exactly\n");
        pass++;
    } else {
        printf("FAIL: output mismatch (see diffs above)\n");
        // Still count it as partial
        int matching = 0;
        for (int i = 0; i < 80; i++) if (rtl_output[i] == ref[i]) matching++;
        printf("  Matching: %d/80 columns\n", matching);
        fail++;
    }

    printf("\ndda_core: %d PASS, %d FAIL\n", pass, fail);
    delete dut;
    return fail ? 1 : 0;
}
